def main_gui():
    import gi
    gi.require_version("Gtk", "4.0")
    gi.require_version("Adw", "1")
    from gi.repository import Adw, GLib, Gtk

    def in_thread(work, done=None):
        def target():
            result = work()
            if done:
                GLib.idle_add(done, result)
        threading.Thread(target=target, daemon=True).start()

    class Window(Adw.ApplicationWindow):
        def __init__(self, app):
            super().__init__(application=app, title="Pinna", default_width=620, default_height=860)
            self.s = load_settings()
            self.loading = True
            self.pending = {}

            self.toasts = Adw.ToastOverlay()
            view = Adw.ToolbarView()
            header = Adw.HeaderBar()
            self.battery = Gtk.Label(css_classes=["dim-label"])
            header.pack_end(self.battery)
            view.add_top_bar(header)
            page = Adw.PreferencesPage()
            view.set_content(page)
            self.toasts.set_child(view)
            self.set_content(self.toasts)

            # --- Headset
            dev = Adw.PreferencesGroup(title="Headset")
            page.add(dev)
            self.status = Adw.ActionRow(title="PRO X 2 LIGHTSPEED")
            self.grant = Gtk.Button(label="Grant access", valign=Gtk.Align.CENTER, css_classes=["suggested-action"])
            self.grant.connect("clicked", self.on_grant)
            self.status.add_suffix(self.grant)
            dev.add(self.status)

            self.sidetone = self.scale_row(dev, "Sidetone", "Hear your own voice in the headset",
                                           0, 100, 1, self.s["sidetone"], self.on_sidetone)
            self.auto_off = Adw.SpinRow.new_with_range(0, 90, 5)
            self.auto_off.set_title("Auto power-off")
            self.auto_off.set_subtitle("Minutes of silence before the headset switches off (0 = never)")
            self.auto_off.set_value(self.s["auto_off"])
            self.auto_off.connect("notify::value", self.on_auto_off)
            dev.add(self.auto_off)

            # --- Sound
            snd = Adw.PreferencesGroup(title="Sound")
            page.add(snd)
            self.surround = Adw.SwitchRow(
                title="Virtual surround",
                subtitle="7.1 rendered for headphones. Makes the headset the default output while on.")
            self.surround.set_active(self.s["surround"])
            self.surround.set_sensitive(hrir_file(self.s["surround_profile"]) is not None)
            self.surround.connect("notify::active", self.on_toggle, "surround")
            snd.add(self.surround)

            self.profiles = list(SURROUND_PROFILES)
            self.profile = Adw.ComboRow(title="Surround profile", subtitle="How the virtual speakers and room sound",
                                        model=Gtk.StringList.new(self.profiles))
            self.profile.set_selected(self.profiles.index(self.s["surround_profile"])
                                      if self.s["surround_profile"] in self.profiles else 0)
            self.profile.connect("notify::selected", self.on_profile)
            snd.add(self.profile)

            self.eq = Adw.SwitchRow(title="Equaliser", subtitle="Applies to everything played on the headset")
            self.eq.set_active(self.s["eq"])
            self.eq.connect("notify::active", self.on_toggle, "eq")
            snd.add(self.eq)

            self.presets = list(EQ_PRESETS) + [CUSTOM]
            self.preset = Adw.ComboRow(title="Preset", model=Gtk.StringList.new(self.presets))
            self.preset.set_selected(self.presets.index(self.s["eq_preset"])
                                     if self.s["eq_preset"] in self.presets else 0)
            self.preset.connect("notify::selected", self.on_preset)
            snd.add(self.preset)

            bands = Gtk.Box(spacing=4, homogeneous=True, margin_top=12, margin_bottom=12,
                            margin_start=12, margin_end=12)
            self.band_scales = []
            for i, freq in enumerate(EQ_FREQS):
                col = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=4)
                sc = Gtk.Scale.new_with_range(Gtk.Orientation.VERTICAL, -12, 12, 0.5)
                sc.set_inverted(True)
                sc.set_size_request(-1, 170)
                sc.set_value(self.s["eq_gains"][i])
                sc.add_mark(0, Gtk.PositionType.RIGHT, None)
