# ---------------------------------------------------------------- helpers

def run(cmd, timeout=10):
    """Run a command; return (ok, stdout). Never raises."""
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        return p.returncode == 0, p.stdout
    except (OSError, subprocess.TimeoutExpired):
        return False, ""


def bundled(*candidates):
    for c in candidates:
        if c and os.path.exists(c):
            return c
    return None


def headsetcontrol_bin():
    return bundled(
        os.path.join(APPDIR, "usr/bin/headsetcontrol") if APPDIR else None,
        os.path.join(HERE, "vendor/headsetcontrol-appimage/squashfs-root/usr/bin/headsetcontrol"),
        shutil.which("headsetcontrol"),
    )


def rnnoise_plugin():
    """Copy the bundled plugin to a stable path (the AppImage mount point changes per run)."""
    src = bundled(
        os.path.join(APPDIR, "usr/lib/ladspa/librnnoise_ladspa.so") if APPDIR else None,
        os.path.join(HERE, "vendor/rnnoise/linux-rnnoise/ladspa/librnnoise_ladspa.so"),
    )
    dst = os.path.join(DATA_DIR, "librnnoise_ladspa.so")
    if src and (not os.path.exists(dst) or os.path.getsize(dst) != os.path.getsize(src)):
        os.makedirs(DATA_DIR, exist_ok=True)
        shutil.copy2(src, dst)
    return dst if os.path.exists(dst) else None


def hrir_file(profile):
    """Copy the profile's impulse response to a stable path and return it."""
    name = SURROUND_PROFILES.get(profile, "dtshx") + ".wav"
    src = bundled(
        os.path.join(APPDIR, "usr/share/pinna/hrir", name) if APPDIR else None,
        os.path.join(HERE, "vendor/hesuvi/extracted/HeSuVi/hrir", name),
    )
    dst = os.path.join(DATA_DIR, "hrir", name)
    if src and (not os.path.exists(dst) or os.path.getsize(dst) != os.path.getsize(src)):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
    return dst if os.path.exists(dst) else None


def load_settings():
    s = dict(DEFAULTS)
    try:
        with open(SETTINGS_PATH) as f:
            s.update(json.load(f))
    except (OSError, ValueError):
        pass
    return s


def save_settings(s):
    os.makedirs(os.path.dirname(SETTINGS_PATH), exist_ok=True)
    with open(SETTINGS_PATH, "w") as f:
        json.dump(s, f, indent=2)


# --------------------------------------------------------------- pipewire

def pw_nodes():
    """Map node.name -> id for all PipeWire nodes."""
    ok, out = run(["pw-dump"])
    nodes = {}
    if ok:
        try:
            for o in json.loads(out):
                if o.get("type") == "PipeWire:Interface:Node":
                    name = o.get("info", {}).get("props", {}).get("node.name")
                    if name:
                        nodes[name] = o["id"]
        except ValueError:
            pass
    return nodes


def detect_devices(s):
    """Remember the headset's node names so config still works while it is switched off."""
    nodes = pw_nodes()
    for key, prefix in (("sink", SINK_PREFIX), ("source", SOURCE_PREFIX)):
        found = next((n for n in nodes if n.startswith(prefix)), None)
        if found:
            s[key] = found
    return bool(s["sink"])


def eq_preamp(gains):
    return -max(0.0, max(gains))


def eq_module(s):
    names = ["eq_pre"] + ["eq_band_%d" % i for i in range(1, len(EQ_FREQS) + 1)]
    # A high shelf at 0 Hz is a plain gain stage: it pulls the level down by the
    # largest boost so boosted bands cannot clip.
    nodes = ['{ type = builtin name = eq_pre label = bq_highshelf control = { "Freq" = 0.0 "Q" = 1.0 "Gain" = %.1f } }'
             % eq_preamp(s["eq_gains"])]
    for name, freq, gain in zip(names[1:], EQ_FREQS, s["eq_gains"]):
        nodes.append('{ type = builtin name = %s label = bq_peaking control = { "Freq" = %.1f "Q" = 1.41 "Gain" = %.1f } }'
                     % (name, freq, gain))
    links = ['{ output = "%s:Out" input = "%s:In" }' % (a, b) for a, b in zip(names, names[1:])]
    return """    { name = libpipewire-module-filter-chain
        flags = [ nofail ]
        args = {
            node.description = "Headset equaliser"
            media.name       = "Headset equaliser"
            filter.graph = {
                nodes = [
                    %s
                ]
                links = [
                    %s
                ]
            }
            audio.channels = 2
            audio.position = [ FL FR ]
            capture.props = {
                node.name   = "%s"
                media.class = Audio/Sink
                filter.smart = true
                filter.smart.name = "pinna-eq"
                filter.smart.target = { node.name = "%s" }
            }
            playback.props = {
                node.name    = "effect_output.hp_eq"
                node.passive = true
                target.object = "%s"
            }
        }
    }""" % ("\n                    ".join(nodes), "\n                    ".join(links),
            EQ_NODE, s["sink"], s["sink"])


SPEAKERS = ["FL", "FR", "FC", "LFE", "RL", "RR", "SL", "SR"]
# (speaker, ear) -> channel in a HeSuVi impulse-response file. LFE reuses the centre.
HRIR_CHANNELS = {
    ("FL", "L"): 0, ("FL", "R"): 1, ("SL", "L"): 2, ("SL", "R"): 3, ("RL", "L"): 4, ("RL", "R"): 5,
    ("FC", "L"): 6, ("FR", "R"): 7, ("FR", "L"): 8, ("SR", "R"): 9, ("SR", "L"): 10,
    ("RR", "R"): 11, ("RR", "L"): 12, ("FC", "R"): 13, ("LFE", "L"): 6, ("LFE", "R"): 13,
}


def surround_module(s, hrir):
    nodes, links = [], []
    for i, ch in enumerate(SPEAKERS, 1):
        nodes.append("{ type = builtin label = copy name = copy%s }" % ch)
        for ear in "LR":
            conv = "conv%s_%s" % (ch, ear)
            nodes.append('{ type = builtin label = convolver name = %s config = { filename = "%s" channel = %d } }'
                         % (conv, hrir, HRIR_CHANNELS[(ch, ear)]))
            links.append('{ output = "copy%s:Out" input = "%s:In" }' % (ch, conv))
            links.append('{ output = "%s:Out" input = "mix%s:In %d" }' % (conv, ear, i))
    nodes.append("{ type = builtin label = mixer name = mixL }")
    nodes.append("{ type = builtin label = mixer name = mixR }")
    inputs = " ".join('"copy%s:In"' % ch for ch in SPEAKERS)
    return """    { name = libpipewire-module-filter-chain
        flags = [ nofail ]
        args = {
            node.description = "Headset virtual surround"
            media.name       = "Headset virtual surround"
            filter.graph = {
                nodes = [
                    %s
                ]
                links = [
                    %s
                ]
                inputs  = [ %s ]
                outputs = [ "mixL:Out" "mixR:Out" ]
            }
            capture.props = {
                node.name      = "%s"
                media.class    = Audio/Sink
                audio.channels = 8
                audio.position = [ %s ]
            }
            playback.props = {
                node.name      = "effect_output.hp_surround"
                node.passive   = true
                audio.channels = 2
                audio.position = [ FL FR ]
                target.object  = "%s"
            }
        }
    }""" % ("\n                    ".join(nodes), "\n                    ".join(links), inputs,
            SURROUND_NODE, " ".join(SPEAKERS), s["sink"])


def mic_module(s, plugin):
    return """    { name = libpipewire-module-filter-chain
        flags = [ nofail ]
        args = {
            node.description = "Headset microphone (noise suppressed)"
            media.name       = "Headset microphone (noise suppressed)"
            filter.graph = {
                nodes = [
                    { type = ladspa name = rnnoise plugin = "%s" label = noise_suppressor_mono
                      control = { "VAD Threshold (%%)" = %.1f } }
                ]
            }
            audio.channels = 1
            audio.position = [ MONO ]
            capture.props = {
                node.name    = "effect_input.hp_mic"
                node.passive = true
                target.object = "%s"
            }
            playback.props = {
                node.name   = "%s"
                media.class = Audio/Source
                filter.smart = true
                filter.smart.name = "pinna-mic"
                filter.smart.target = { node.name = "%s" }
            }
        }
    }""" % (plugin, float(s["mic_vad"]), s["source"], MIC_NODE, s["source"])


def filter_module(s, name):
    """Return the module text for one filter, or '' if it is off or unavailable."""
    if name == "eq" and s["eq"] and s["sink"]:
        return eq_module(s)
    if name == "surround" and s["surround"] and s["sink"]:
        hrir = hrir_file(s["surround_profile"])
        if hrir:
            return surround_module(s, hrir)
    if name == "mic" and s["mic_ns"] and s["source"]:
        plugin = rnnoise_plugin()
        if plugin:
            return mic_module(s, plugin)
    return ""


def conf_path(name):
    return os.path.join(PW_DIR, "pinna-%s.conf" % name)


def write_conf(s, name):
    module = filter_module(s, name)
    if module:
        os.makedirs(PW_DIR, exist_ok=True)
        with open(conf_path(name), "w") as f:
            f.write(CONF_HEAD + module + "\n]\n")
    elif os.path.exists(conf_path(name)):
        os.remove(conf_path(name))
    return bool(module)


def ensure_unit():
    current = ""
    if os.path.exists(UNIT_PATH):
        with open(UNIT_PATH) as f:
            current = f.read()
    if current != UNIT_TEXT:
        os.makedirs(os.path.dirname(UNIT_PATH), exist_ok=True)
        with open(UNIT_PATH, "w") as f:
            f.write(UNIT_TEXT)
        run(["systemctl", "--user", "daemon-reload"])


def wait_for_node(name, tries=15):
    for _ in range(tries):
        node = pw_nodes().get(name)
        if node:
            return node
        time.sleep(0.2)
    return None


def release_surround(s):
    """Move playing streams back to the headset before the surround sink goes away.

    Removing a sink that apps are still playing into makes some of them (browsers)
    stop playback; moving them first keeps the music running.
    """
    nodes = pw_nodes()
    if SURROUND_NODE in nodes and s["sink"] in nodes:
        run(["wpctl", "set-default", str(nodes[s["sink"]])])
        time.sleep(0.5)


def unpin_default():
    """Drop our pin on the default output so the system picks a device again."""
    key = "default.configured.audio.sink"
    _, current = run(["pw-metadata", "-n", "default", "0", key])
    if SURROUND_NODE in current or SINK_PREFIX in current:
        run(["pw-metadata", "-n", "default", "-d", "0", key])


def apply_filters(s, names=FILTERS):
    """Write config for the named filters and start or stop their services."""
    detect_devices(s)
    ensure_unit()
    ok = True
    for name in names:
        unit = UNIT % name
        if name == "surround":
            release_surround(s)
        if write_conf(s, name):
            run(["systemctl", "--user", "enable", unit])
            ok = run(["systemctl", "--user", "restart", unit])[0] and ok
            if name == "surround":
                # 7.1 only reaches the spatializer if apps see an 8-channel default sink.
                node = wait_for_node(SURROUND_NODE)
                if node:
                    run(["wpctl", "set-default", str(node)])
        else:
            run(["systemctl", "--user", "disable", "--now", unit])
            if name == "surround":
                unpin_default()
    save_settings(s)
    return ok


def set_live(node_name, params):
    """Push control values to a running filter without a restart."""
    node = pw_nodes().get(node_name)
    if not node:
        return False
    text = " ".join('"%s" %.1f' % kv for kv in params)
    return run(["pw-cli", "set-param", str(node), "Props", "{ params = [ %s ] }" % text])[0]


def set_eq_live(s):
    params = [("eq_pre:Gain", eq_preamp(s["eq_gains"]))]
    params += [("eq_band_%d:Gain" % i, g) for i, g in enumerate(s["eq_gains"], 1)]
    return set_live(EQ_NODE, params)


def set_mic_live(s):
    return set_live("effect_input.hp_mic", [("rnnoise:VAD Threshold (%)", float(s["mic_vad"]))])


# ----------------------------------------------------------------- device

def hidraw_path():
    for uevent in glob.glob("/sys/class/hidraw/hidraw*/device/uevent"):
        try:
            with open(uevent) as f:
                text = f.read().upper()
        except OSError:
            continue
        if "0000%s:0000%s" % (USB_VENDOR.upper(), USB_PRODUCT.upper()) in text:
            return "/dev/" + uevent.split("/")[4]
    return None


def device_access():
    """Return 'ok', 'denied' or 'absent'."""
    path = hidraw_path()
    if not path:
        return "absent"
    return "ok" if os.access(path, os.R_OK | os.W_OK) else "denied"


def hsc(*args):
    binary = headsetcontrol_bin()
    if not binary:
        return False, ""
    return run([binary, *args], timeout=8)


def read_battery():
    """Return (percent or None, charging bool)."""
    ok, out = hsc("-o", "json")
    if not ok:
        return None, False
    try:
        for dev in json.loads(out).get("devices", []):
            bat = dev.get("battery") or {}
            level = bat.get("level")
            if isinstance(level, int) and level >= 0:
                return level, "CHARGING" in str(bat.get("status", "")).upper()
    except ValueError:
        pass
    return None, False


def grant_access():
    """Install a udev rule (asks for the admin password through polkit)."""
    with tempfile.NamedTemporaryFile("w", suffix=".rules", delete=False) as f:
        f.write(UDEV_RULE)
        tmp = f.name
    ok, _ = run(["pkexec", "sh", "-c",
                 'install -m 644 "$1" "$2" && udevadm control --reload-rules && '
                 "udevadm trigger --subsystem-match=hidraw && udevadm settle --timeout=5",
                 "sh", tmp, UDEV_RULE_PATH], timeout=120)
    os.unlink(tmp)
    return ok


